    /// @brief The replacement glyph: a hollow box, drawn for every code point without a glyph.
    inline constexpr std::uint8_t builtin_replacement_rows[builtin_glyph_height] = {
        0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F,
    };

    /// @brief The seven row bytes of one code point of the built-in face.
    /// @param codepoint The code point; anything outside 32..126 answers the replacement box.
    /// @return The rows, top row first, bit 4 = leftmost column.
    /// @note This reads the built-in table only. It says nothing about any other font family.
    inline constexpr std::array<std::uint8_t, builtin_glyph_height> builtin_glyph_rows(int codepoint) noexcept {
        std::array<std::uint8_t, builtin_glyph_height> rows{};
        const std::uint8_t* source = builtin_replacement_rows;
        if (codepoint >= builtin_first_codepoint && codepoint <= builtin_last_codepoint) {
            source = builtin_glyph_table[codepoint - builtin_first_codepoint];
        }
        for (int row = 0; row < builtin_glyph_height; ++row) {
            rows[static_cast<std::size_t>(row)] = source[row];
        }
        return rows;
    }
