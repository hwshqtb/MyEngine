#ifndef HWSHQTB__METAOBJECT__DYNAMIC_BASE_T_H
#define HWSHQTB__METAOBJECT__DYNAMIC_BASE_T_H

/// @file dynamic_base_t.h
/// @brief Mixin for classes whose meta-object was built at run time.

#include "any_t.h"
#include "meta_info_t.h"
#include "meta_object_t.h"
#include "export.h"

#include <map>
#include <string>
#include <string_view>
#include <vector>

namespace hwshqtb::metaobject {
    /// @brief Mixin that carries a run-time built meta-object and a property bag.
    ///
    /// It deliberately does NOT derive from object_t: a class inherits it *alongside* object_t (or
    /// one of its subclasses), and that pairing is what makes a @c dynamic_xxx — an object whose
    /// meta-object is built at run time. Inheriting it on its own is meaningless: the mixin knows
    /// nothing about being an object, has no parent, no thread and no signals, so the constructor
    /// is protected.
    ///
    /// @code
    /// class dynamic_widget : public object_t, public dynamic_base_t {
    /// public:
    ///     explicit dynamic_widget(const meta_object_t* meta) : dynamic_base_t(meta) { }
    ///     DYNAMIC_BASE
    /// };
    /// @endcode
    ///
    /// @note meta_object() is generated by the OBJECT macro, so a sibling base class cannot override
    ///       it; the final class supplies it — DYNAMIC_BASE expands to exactly that one line, and it
    ///       returns facade().
    /// @note The mixin does not own the meta_object_t: it stores the pointer
    ///       meta_object_builder_t::build() returned, which the process-wide arena keeps alive.
    class HWSHQTB_EXPORT dynamic_base_t {
    public:
        /// @brief Read one value from the bag.
        /// @param name The value name.
        /// @return The stored value; an invalid any_t when absent.
        any_t dynamic_value(std::string_view name) const;

        /// @brief Store one value in the bag.
        /// @param name The value name.
        /// @param value The value to store.
        void set_dynamic_value(std::string_view name, const any_t& value);

        /// @brief Every name currently in the bag.
        /// @return The names, sorted (std::map order).
        std::vector<std::string> dynamic_value_names() const;

    protected:
        /// @brief Construct with a built meta-object.
        /// @param facade The meta-object meta_object_builder_t::build() returned (an arena entry). It must
        ///        outlive this object — the process-wide arena guarantees that for every built type,
        ///        so the object's place in a tree is irrelevant — and it is stored, not copied:
        ///        meta_object_t is neither copyable nor movable.
        /// @note Protected: only a derived dynamic_xxx may be constructed.
        explicit dynamic_base_t(const meta_object_t* facade) noexcept;

        /// @brief The run-time meta-object, for DYNAMIC_BASE to return.
        /// @return The pointer handed to the constructor; never null for a successfully built type.
        /// @note noexcept.
        const meta_object_t* facade() const noexcept;

    private:
        /// @brief The meta-object this instance reports (owned by the process-wide arena).
        const meta_object_t* _facade = nullptr;
        /// @brief Property bag: the storage backend for designer / QML style accessors.
        std::map<std::string, any_t> _values;
    };
}

#endif
